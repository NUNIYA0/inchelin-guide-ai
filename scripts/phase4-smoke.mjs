import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
export async function testPhase4(request){
  const state=r=>r.body.meta.responseModeState,c=r=>state(r).phase1.conditions;
  const lunch=await request('오늘 점심 추천해줘');
  const located=await request('강남역',{state:state(lunch)});
  assert.equal(located.body.restaurants.length,3,'ordinary meal does not require extra consent');
  assert.equal(c(located).requireOpen,false);
  assert.ok(!located.body.suggestions.includes('미확인 후보 보기'));
  assert.ok(located.body.restaurants.every(card=>card.conditionVerification.checks.some(check=>check.key==='visit'&&!check.blocking&&check.status==='unknown')));
  const strict=await request('강남역에서 지금 영업 중인 곳만 찾아줘');
  assert.equal(c(strict).requireOpen,true);assert.equal(strict.body.restaurants.length,0);assert.equal(strict.calls.length,0);
  const first=await request('강남역에서 한식 만 원 이하로 혼자 먹을 거야');
  const accepted=await request('미확인 후보 보기',{state:state(first)});
  assert.equal(accepted.body.restaurants.length,3);
  assert.ok(accepted.body.restaurants.every(card=>card.conditionVerification.checks.some(check=>check.key==='food_category'&&check.status==='confirmed')));
  const radius=await request('500m 안으로',{state:state(accepted)});
  assert.equal(radius.body.restaurants.length,2);assert.ok(!radius.body.suggestions.includes('미확인 후보 보기'));
  const parking=await request('주차 필요한 곳으로',{state:state(radius)});
  assert.equal(parking.body.restaurants.length,0);assert.deepEqual(state(parking).phase1.pendingUnknowns,['parking']);
  assert.ok(!/가격|좌석/.test(parking.body.message),'only newly unknown fields need confirmation');
  const fresh=await request('강남역에서 한식 만 원 이하로 혼자 먹을 거야');
  assert.equal(fresh.body.restaurants.length,0,'consent is not global');
  const demo=await request('강남역',{demoMode:true});
  assert.equal(demo.calls.length,0);assert.equal(demo.body.meta.dataConnectionStatus,'fictional_demo');
  assert.equal(demo.body.restaurants.length,3);assert.equal(new Set(demo.body.restaurants.map(card=>card.id)).size,3);
  const a=demo.body.restaurants.find(card=>card.name==='가상 국밥집 A');
  assert.equal(a.recommendationBundle.representative.id,'demo-a2');assert.equal(a.recommendationBundle.additional.length,2,'records, not distinct people');
  assert.ok(demo.body.restaurants.every(card=>card.isDemo&&!card.naverPlaceUrl&&!card.naverLink));
  const solo=await request('혼자 먹을 거야',{state:state(demo),demoMode:true});
  assert.equal(solo.body.restaurants[0].recommendationBundle.representative.id,'demo-a1');
  const meeting=await request('회식할 거야',{state:state(demo),demoMode:true});
  const meetingConsent=await request('미확인 후보 보기',{state:state(meeting),demoMode:true});
  assert.equal(meetingConsent.body.restaurants[0].recommendationBundle.representative.id,'demo-a2');
  const budget=await request('강남역에서 한식 만 원 이하로 혼자 먹을 거야',{demoMode:true});
  assert.equal(budget.body.restaurants.length,1);assert.equal(budget.body.restaurants[0].registeredFacts.menus[0].priceKRW,9000);
  assert.equal(budget.body.restaurants[0].conditionVerification.status,'confirmed');
  const mixed=await request('미확인 후보 보기',{state:state(budget),demoMode:true});
  assert.equal(mixed.body.restaurants.length,2,'over-budget C is excluded, unknown B is separate');
  assert.ok(mixed.body.restaurants.some(card=>card.conditionVerification.status==='unconfirmed'));
  const open=await request('강남역에서 내일 저녁 7시에 영업하는 곳만 찾아줘',{demoMode:true});
  assert.equal(c(open).visitAt,'2026-10-23T10:00:00.000Z');
  assert.equal(open.body.restaurants.length,1);assert.equal(open.body.restaurants[0].name,'가상 국밥집 A');
  const ordinary=await request('강남역에서 내일 저녁 먹을 곳 추천해줘',{demoMode:true});
  assert.equal(ordinary.body.restaurants.length,3);assert.equal(c(ordinary).requireOpen,false);
  const detail=await request('첫 번째 집 메뉴와 가격 알려줘',{state:state(demo),demoMode:true});
  assert.match(detail.body.message,/국밥 9,000원/);assert.ok(!/메뉴·가격.*없어요/.test(detail.body.message));
  const back=await request('강남역',{state:state(demo)});
  assert.ok(back.body.restaurants.every(card=>!card.isDemo&&!/가상/.test(card.name)),'demo state cannot enter normal results');
  const normalConfig=JSON.parse(await readFile(new URL('../data/recommendation-source.json',import.meta.url),'utf8'));
  assert.equal(normalConfig.connected,false);assert.equal(normalConfig.enabled,false);
  return {demo:demo.body,demoBudget:budget.body};
}
