import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
export async function testPhase4(request){
  const state=r=>r.body.meta.responseModeState,c=r=>state(r).phase1.conditions;
  const lunch=await request('오늘 점심 추천해줘');
  const located=await request('강남역',{state:state(lunch)});
  assert.equal(located.body.restaurants.length,3,'ordinary meal does not require extra consent');
  assert.equal(c(located).requireOpen,false);
  assert.ok(!located.body.suggestions.includes('미확인 후보 보기'));
  assert.ok(located.body.restaurants.every(card=>card.conditionVerification.checks.some(check=>check.key==='visit'&&!check.blocking&&check.status==='unknown')));
  const strict=await request('강남역에서 지금 영업 중인 곳만 찾아줘');
  assert.equal(c(strict).requireOpen,true);assert.equal(strict.body.restaurants.length,0);assert.equal(strict.calls.length,0);
  const first=await request('강남역에서 한식 만 원 이하로 혼자 먹을 거야');
  const accepted=await request('미확인 후보 보기',{state:state(first)});
  assert.equal(accepted.body.restaurants.length,3);
  assert.ok(accepted.body.restaurants.every(card=>card.conditionVerification.checks.some(check=>check.key==='food_category'&&check.status==='confirmed')));
  const radius=await request('500m 안으로',{state:state(accepted)});
  assert.equal(radius.body.restaurants.length,2);assert.ok(!radius.body.suggestions.includes('미확인 후보 보기'));
  const parking=await request('주차 필요한 곳으로',{state:state(radius)});
  assert.equal(parking.body.restaurants.length,0);assert.deepEqual(state(parking).phase1.pendingUnknowns,['parking']);
  assert.ok(!/가격|좌석/.test(parking.body.message),'only newly unknown fields need confirmation');
  const fresh=await request('강남역에서 한식 만 원 이하로 혼자 먹을 거야');
  assert.equal(fresh.body.restaurants.length,0,'consent is not global');
  const retired=await request('강남역',{demoMode:true,state:{phase1:{demoMode:true},lastCards:[{id:'demo-a',name:'가상 국밥집 A',isDemo:true}]}});
  assert.equal(retired.calls.length,1,'retired demo parameter cannot bypass real search');
  assert.ok(retired.body.restaurants.every(card=>!card.isDemo&&!/가상/.test(card.name)));
  assert.equal(retired.body.meta.demoMode,undefined);
  const html=await readFile(new URL('../dist/index.html',import.meta.url),'utf8');
  assert.ok(!/demo-entry|demoBanner|DEMO_MODE|가상 데이터/.test(html),'no demonstration entry or copy');
  const bundle=await readFile(new URL('../build/dist/server/index.js',import.meta.url),'utf8');
  assert.ok(!/demoRecommendationSource|가상 추천인|fictional_demo/.test(bundle),'no deployable fictional catalogue');
  return {};
}
